# Да се създаде функция, която извежда таблицата за умножение (от 1 до 10) с помощта на два вложени while цикъла.
# Между числата да има табулация (tab), а всяка нова редица да е на нов ред.
def task3(i):
    while i <= 10:
        j = 1
        while j <= 10:
            print(i,'*',j, '=',i * j, end=" \t")
            j += 1
        print()
        i += 1
task3(1)